const mongoose = require('mongoose');
const bcrypt = require('bcryptjs');

const userSchema = new mongoose.Schema({
  name: { type: String, required: true },
  email: { type: String, required: true, unique: true },
  password: { type: String, required: true },
  role: { type: String, enum: ['user', 'admin'], default: 'user' },
  package: { type: mongoose.Schema.Types.ObjectId, ref: 'Package', default: null },
  packageExpiresAt: { type: Date },
  apiKey: { type: String, unique: true, sparse: true }, // sparse: true allows multiple null values
  apiAccessStatus: {
    type: String,
    enum: ['none', 'requested', 'approved'],
    default: 'none',
  },
}, { timestamps: true });

// Hash password before saving
userSchema.pre('save', async function (next) {
  if (!this.isModified('password')) return next();
  const salt = await bcrypt.genSalt(10);
  this.password = await bcrypt.hash(this.password, salt);
  next();
});

// Method to compare password
userSchema.methods.matchPassword = async function (enteredPassword) {
  return await bcrypt.compare(enteredPassword, this.password);
};

module.exports = mongoose.model('User', userSchema);
